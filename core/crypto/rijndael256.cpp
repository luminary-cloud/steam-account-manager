// Round constant: rc[i] is the byte for Rcon iteration i. Computed as
// rc[1]=1, rc[i] = xtime(rc[i-1]). We need indices 1..15 for Nk=8, Nr=14.
constexpr std::uint8_t kRcon[16] = {
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40,
    0x80, 0x1B, 0x36, 0x6C, 0xD8, 0xAB, 0x4D, 0x9A,
};

constexpr int kNb = 8;     // block size in 32-bit words: 32-byte block
constexpr int kNk = 8;     // key size in 32-bit words: 32-byte key
constexpr int kNr = 14;    // rounds for Nb=8, Nk=8
constexpr int kBlockSize = kNb * 4;            // 32
constexpr int kKeySize   = kNk * 4;            // 32
constexpr int kRoundKeyBytes = (kNr + 1) * kBlockSize;  // 480

// ShiftRows offsets for Nb=8 (Rijndael spec table 2). Row r shifts left by C(r).
// For Nb in {4,5,6}: {0,1,2,3}; for Nb=7: {0,1,2,4}; for Nb=8: {0,1,3,4}.
constexpr int kShiftOffsets[4] = {0, 1, 3, 4};

// xtime: multiplication by x in GF(2^8) with the AES reduction polynomial.
inline std::uint8_t xtime(std::uint8_t b) {
    return static_cast<std::uint8_t>((b << 1) ^ ((b & 0x80) ? 0x1B : 0x00));
}

// Multiply a, b in GF(2^8) using the AES reduction polynomial.
std::uint8_t gmul(std::uint8_t a, std::uint8_t b) {
    std::uint8_t r = 0;
    for (int i = 0; i < 8; ++i) {
        if (b & 1) r ^= a;
        a = xtime(a);
        b >>= 1;
    }
    return r;
}

// Key expansion: input 32-byte key -> 480 bytes of round-key material.
//
// Operates on 32-bit "words" (4 bytes each). For Rijndael with Nk=8 there is
// an extra SubWord step every Nk words (the "Nk>6" branch in the spec).
void key_expansion(std::span<const std::uint8_t> key,
                   std::array<std::uint8_t, kRoundKeyBytes>& w) {
    std::memcpy(w.data(), key.data(), kKeySize);

    const int total_words = kNb * (kNr + 1);  // 120 words
    for (int i = kNk; i < total_words; ++i) {
        std::uint8_t t[4];
        std::memcpy(t, &w[(i - 1) * 4], 4);

        if (i % kNk == 0) {
            // RotWord: rotate left by 1 byte.
            const std::uint8_t r0 = t[0];
            t[0] = t[1]; t[1] = t[2]; t[2] = t[3]; t[3] = r0;
            // SubWord.
            t[0] = kSbox[t[0]];
            t[1] = kSbox[t[1]];
            t[2] = kSbox[t[2]];
            t[3] = kSbox[t[3]];
            // XOR Rcon.
            t[0] ^= kRcon[i / kNk];
        } else if (kNk > 6 && i % kNk == 4) {
            // Extra SubWord every Nk words when Nk > 6.
            t[0] = kSbox[t[0]];
            t[1] = kSbox[t[1]];
            t[2] = kSbox[t[2]];
            t[3] = kSbox[t[3]];
        }

        for (int j = 0; j < 4; ++j) {
            w[i * 4 + j] = w[(i - kNk) * 4 + j] ^ t[j];
        }
    }
}

// State is column-major: state[c*4 + r] holds row r, column c.
using State = std::array<std::uint8_t, kBlockSize>;

void add_round_key(State& s, const std::uint8_t* round_key) {
    for (int i = 0; i < kBlockSize; ++i) s[i] ^= round_key[i];
}

void inv_sub_bytes(State& s) {
    for (int i = 0; i < kBlockSize; ++i) s[i] = kInvSbox[s[i]];
}

void inv_shift_rows(State& s) {
    // Inverse ShiftRows: row r shifts RIGHT by kShiftOffsets[r].
    // Rebuild row by row to avoid in-place overwrite hazards.
    for (int r = 1; r < 4; ++r) {
        const int shift = kShiftOffsets[r];
        std::uint8_t tmp[kNb];
        for (int c = 0; c < kNb; ++c) tmp[c] = s[c * 4 + r];
        for (int c = 0; c < kNb; ++c) {
            const int src = (c - shift + kNb) % kNb;
            s[c * 4 + r] = tmp[src];
        }
    }
}

// InvMixColumns applied column-by-column. Standard inverse MixColumns matrix:
//   [ 0E 0B 0D 09 ]
//   [ 09 0E 0B 0D ]
//   [ 0D 09 0E 0B ]
//   [ 0B 0D 09 0E ]
void inv_mix_columns(State& s) {
    for (int c = 0; c < kNb; ++c) {
        const std::uint8_t a0 = s[c * 4 + 0];
        const std::uint8_t a1 = s[c * 4 + 1];
        const std::uint8_t a2 = s[c * 4 + 2];
        const std::uint8_t a3 = s[c * 4 + 3];
        s[c * 4 + 0] = static_cast<std::uint8_t>(
            gmul(a0, 0x0E) ^ gmul(a1, 0x0B) ^ gmul(a2, 0x0D) ^ gmul(a3, 0x09));
        s[c * 4 + 1] = static_cast<std::uint8_t>(
            gmul(a0, 0x09) ^ gmul(a1, 0x0E) ^ gmul(a2, 0x0B) ^ gmul(a3, 0x0D));
        s[c * 4 + 2] = static_cast<std::uint8_t>(
            gmul(a0, 0x0D) ^ gmul(a1, 0x09) ^ gmul(a2, 0x0E) ^ gmul(a3, 0x0B));
        s[c * 4 + 3] = static_cast<std::uint8_t>(
            gmul(a0, 0x0B) ^ gmul(a1, 0x0D) ^ gmul(a2, 0x09) ^ gmul(a3, 0x0E));
    }
}

void decrypt_block(const std::uint8_t in[kBlockSize],
                   std::uint8_t out[kBlockSize],
                   const std::array<std::uint8_t, kRoundKeyBytes>& w) {
    State s;
    std::memcpy(s.data(), in, kBlockSize);

    add_round_key(s, &w[kNr * kBlockSize]);

    for (int round = kNr - 1; round >= 1; --round) {
        inv_shift_rows(s);
        inv_sub_bytes(s);
        add_round_key(s, &w[round * kBlockSize]);
        inv_mix_columns(s);
    }

    inv_shift_rows(s);
    inv_sub_bytes(s);
    add_round_key(s, &w[0]);

    std::memcpy(out, s.data(), kBlockSize);
}

