std::vector<std::uint8_t> rijndael256_cbc_pkcs7_decrypt(
    std::span<const std::uint8_t> key,
    std::span<const std::uint8_t> iv,
    std::span<const std::uint8_t> ciphertext) {

    if (key.size() != kKeySize)
        throw std::invalid_argument("rijndael256: key must be 32 bytes");
    if (iv.size() != kBlockSize)
        throw std::invalid_argument("rijndael256: iv must be 32 bytes");
    if (ciphertext.empty() || ciphertext.size() % kBlockSize != 0)
        throw CbcPaddingError("rijndael256: ciphertext length must be a multiple of 32");

    std::array<std::uint8_t, kRoundKeyBytes> round_keys{};
    key_expansion(key, round_keys);

    std::vector<std::uint8_t> out(ciphertext.size());
    std::uint8_t prev[kBlockSize];
    std::memcpy(prev, iv.data(), kBlockSize);

    for (std::size_t off = 0; off < ciphertext.size(); off += kBlockSize) {
        std::uint8_t block_in[kBlockSize];
        std::uint8_t block_out[kBlockSize];
        std::memcpy(block_in, ciphertext.data() + off, kBlockSize);
        decrypt_block(block_in, block_out, round_keys);
        for (int i = 0; i < kBlockSize; ++i) {
            out[off + i] = block_out[i] ^ prev[i];
        }
        std::memcpy(prev, block_in, kBlockSize);
    }

    // PKCS#7 unpad against the 32-byte block size.
    const std::uint8_t pad = out.back();
    if (pad == 0 || pad > kBlockSize || pad > out.size())
        throw CbcPaddingError("rijndael256: invalid PKCS#7 padding");
    for (std::size_t i = out.size() - pad; i < out.size(); ++i) {
        if (out[i] != pad)
            throw CbcPaddingError("rijndael256: corrupt PKCS#7 padding");
    }
    out.resize(out.size() - pad);
    return out;
}

